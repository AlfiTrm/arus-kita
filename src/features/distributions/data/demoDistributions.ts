type DistributionOverrides = Pick<Distribution, "id"> &
  Partial<Pick<Distribution, "title" | "item_summary" | "kind" | "status" | "captured_at" | "total_amount" | "donor_count" | "reference_code">>;

function repeatDelivery(sourceId: string, overrides: DistributionOverrides): Omit<Distribution, "post_id"> {
  const source = BASE_DISTRIBUTIONS.find((item) => item.id === sourceId);
  if (!source) throw new Error(`Unknown distribution source: ${sourceId}`);
  return { ...source, ...overrides };
}

